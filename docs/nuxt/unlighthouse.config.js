/**
 * Unlighthouse configuration: a Lighthouse audit over the whole generated site.
 *
 * Run by the `audit:seo` CI job, which generates the site, serves `dist/` on
 * :4000 and audits it. Never imported by the Nuxt build. That separation is
 * deliberate and load bearing: unlighthouse needs Node 18+, this site is pinned
 * to Node 16, and the audit only ever talks to the built site over HTTP. The CI
 * job therefore runs on its own Node image and never touches the frozen
 * toolchain.
 *
 * Plain CommonJS with no helper import, so it stays decoupled from the
 * unlighthouse runtime API.
 */

/**
 * Every route, read out of the generated sitemap in `dist/`.
 *
 * Taken from the build being served rather than from `content/`, because the
 * two are not both present. `content/api` is generated by docgen and
 * gitignored, and the CI job that runs this audit receives only `dist/` as an
 * artifact, so reading `content/` there found the 20 committed files and
 * nothing else: 69 routes audited in CI against 129 locally, reported as a
 * success both times.
 *
 * Reading `dist/sitemap.xml` makes audit coverage and sitemap coverage the same
 * set by construction, and it depends on nothing the audit is not already
 * serving.
 *
 * Resolved once at config load rather than supplied as a callback: the callback
 * form is not read by this version, and with the crawler disabled alongside it
 * the audit fell through to 4 routes while still exiting 0.
 *
 * @returns {string[]} Route paths, or an empty list if the sitemap is missing.
 */
function sitemapRoutes() {
  try {
    const fs = require('fs')
    const path = require('path')
    const xml = fs.readFileSync(path.join(__dirname, 'dist', 'sitemap.xml'), 'utf8')

    return (xml.match(/<loc>([^<]+)<\/loc>/g) || [])
      // Strip the canonical origin. It is why the scanner cannot be pointed at
      // this file directly: unlighthouse discards sitemap entries whose origin
      // differs from the site it is auditing, which it always will here, since
      // the audit serves the build on localhost.
      .map((tag) => tag.replace(/<\/?loc>/g, '').replace(/^https?:\/\/[^/]+/, ''))
      .map((route) => route || '/')
  } catch (e) {
    // Never take the audit down over the route list; the crawler below still
    // finds the linked pages.
    return []
  }
}

/**
 * Reduce a route list to a representative sample, grouped by page shape.
 *
 * Routes are grouped by their section and depth, which is a good proxy for
 * which page template renders them, then taken round robin from each group.
 * That guarantees every template survives the sample: taking the first N of a
 * sorted list would return 25 API pages and never audit the homepage.
 *
 * Deterministic, so two runs of the same build audit the same routes and their
 * numbers can be compared.
 *
 * @param {string[]} routes - Every route, in sitemap order.
 * @param {number} limit - Maximum routes to keep; 0 keeps all of them.
 * @returns {string[]} The sampled routes.
 */
function sampleRoutes(routes, limit) {
  if (!limit || routes.length <= limit) return routes

  const groups = new Map()
  routes.forEach((route) => {
    const segments = route.split('/').filter(Boolean)
    const key = (segments[0] || 'home') + ':' + segments.length
    if (!groups.has(key)) groups.set(key, [])
    groups.get(key).push(route)
  })

  const buckets = [...groups.keys()].sort().map((key) => groups.get(key))
  const sample = []
  for (let i = 0; sample.length < limit; i++) {
    const before = sample.length
    for (const bucket of buckets) {
      if (i >= bucket.length || sample.length >= limit) continue
      sample.push(bucket[i])
    }
    // Every bucket is exhausted; nothing further to take.
    if (sample.length === before) break
  }

  return sample.sort()
}

/**
 * Routes to audit, sampled when UNLIGHTHOUSE_SAMPLE asks for it.
 *
 * The two pipelines audit different amounts on purpose. GitHub runs the full
 * set on a dedicated ephemeral runner and is the authoritative baseline. GitLab
 * samples, because its runner shares a host with other work that has repeatedly
 * taken the load average past 400, and a full audit there failed three times
 * over: orphaned browsers, a Chromium OOM, and a single route exceeding its
 * timeout. None of those said anything about the site.
 */
const routes = sampleRoutes(sitemapRoutes(), Number(process.env.UNLIGHTHOUSE_SAMPLE || 0))

module.exports = {
  site: 'http://localhost:4000',

  // One Chromium per worker, and unlighthouse defaults this to the host's core
  // count. On an 18-core machine that is 18 concurrent browsers, which exhausts
  // memory and takes the workers down mid-audit with ECONNREFUSED against their
  // own devtools ports. Two was still too many on the shared runner: the audit
  // died with "Page crashed!" partway through a run, which is Chromium running
  // out of memory rather than anything about the page.
  puppeteerClusterOptions: {
    // Concurrent browsers. One on a shared runner, more where the runner is
    // dedicated; each pipeline sets what its hardware can carry.
    maxConcurrency: Number(process.env.UNLIGHTHOUSE_CONCURRENCY || 1),

    // Per-route budget, raised from the 300000 default. The failure it fixes is
    // "Timeout hit: 300000" from puppeteer-cluster: a single page took longer
    // than five minutes to audit, not because the page is slow but because the
    // runner shares a host that reached a load average above 400. This does not
    // make a genuinely broken page pass; it stops a busy host being reported as
    // a site failure. The job timeout is the real ceiling.
    timeout: 900000,
  },

  puppeteerOptions: {
    // Chromium's sandbox needs unprivileged user namespaces, which CI
    // containers and this devcontainer both withhold; without these it aborts
    // with "No usable sandbox!" before loading a page. Safe here because the
    // only thing being rendered is our own freshly built site.
    args: ['--no-sandbox', '--disable-setuid-sandbox', '--disable-dev-shm-usage'],

    // Use an already-installed Chromium when one is named, rather than the
    // x86_64 build unlighthouse downloads for itself. On an arm64 runner that
    // download launches under Rosetta and dies with "failed to open elf at
    // /lib64/ld-linux-x86-64.so.2" before any page is scanned. Setting
    // CHROME_PATH alone is not enough, it has to reach puppeteer; the CI job
    // points it at Playwright's native arm64 build.
    ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}),
  },

  // Parsed out of dist/sitemap.xml with the origin stripped. See sitemapRoutes
  // above for why the scanner cannot simply be pointed at that file.
  urls: routes,

  scanner: {
    // Left enabled deliberately, as a floor rather than the plan. With it off,
    // a failure to read the route list above degrades to a silent near-empty
    // audit: measured 4 routes scanned and still exiting 0, which reads as a
    // pass. Crawling on top of a complete list costs nothing, since it only
    // rediscovers routes already queued.
    crawler: true,

// No dynamicSampling here on purpose. Supplying `urls` turns unlighthouse's
    // own sampling off, along with the sitemap, robots and the crawler, so
    // setting it would be a no-op that reads as a working cap. Sampling is done
    // in sampleRoutes above instead, where it can guarantee template coverage.
    //
    // Coverage is worth paying for where the hardware allows it. Over the
    // crawled subset color-contrast read as 40 pages; over the full set, 120.
    // Same defect, three times the blast radius, and only the full run gives a
    // number worth quoting.
  },

  ci: {
    // Deliberately 0 until a baseline exists. A guessed threshold either fails
    // the first run for no reason or is set so low it never catches anything.
    // The first green run's numbers are what this should be set from.
    budget: 0,
  },
}
