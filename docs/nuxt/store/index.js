const sectionChildren = (index) => index.map((o) => ({
  component: "NuxtLink",
  text: o.title,
  props: { to: o.path.replace("/README", "") },
}));

export const actions = {
  async nuxtServerInit({ commit }, { $content }) {
    try {
      // Add Druxt modules to Vuex store.
      const modulesIndex = await $content("api/README").only("toc").fetch()
      const modules = await Promise.all(modulesIndex.toc
        .map((o) => o.id.split("-").slice(1).join("-") || o.id)
        .filter((id) => id !== "docgen" && id !== "test-utils")
        .map((id) =>
          $content(`modules/${id}/README`)
            .only(["description", "dir", "title"])
            .fetch()
            .catch(() => null)
        )
      )
      commit("setModules", modules.filter(Boolean));

      // Add Modules menu children to the vuex store.
      const moduleChildren = modules
        .map((o) => ({
          component: "NuxtLink",
          text: o.title,
          props: { to: o.dir },
        }));
      commit("addMenuChildren", { children: moduleChildren, parent: "/modules" });

      // Add Tutorials menu children to the Vuex store.
      const tutorialsIndex = await $content("tutorials")
        .sortBy("weight")
        .only(["path", "title", "weight"])
        .fetch();
      commit("addMenuChildren", {
        children: sectionChildren(tutorialsIndex),
        parent: "/tutorials",
      });

      // Add How-to guides menu children to the Vuex store.
      const howToIndex = await $content("how-to")
        .sortBy("weight")
        .only(["path", "title", "weight"])
        .fetch();
      commit("addMenuChildren", {
        children: sectionChildren(howToIndex),
        parent: "/how-to",
      });

      // Add Concepts (explanation) menu children to the Vuex store.
      const explanationIndex = await $content("explanation")
        .sortBy("weight")
        .only(["path", "title", "weight"])
        .fetch();
      commit("addMenuChildren", {
        children: sectionChildren(explanationIndex),
        parent: "/explanation",
      });

      // Add Components menu children to the Vuex store: top-level component
      // pages generated by docgen under api/packages/*/components/.
      const componentDocs = await $content("api/packages", { deep: true })
        .only(["path", "title"])
        .fetch();
      const componentChildren = componentDocs
        .filter((o) => /\/components\/[^/]+$/.test(o.path))
        .sort((a, b) => (a.title < b.title ? -1 : 1))
        .map((o) => ({
          component: "NuxtLink",
          text: o.title,
          props: { to: o.path },
        }));
      commit("addMenuChildren", { children: componentChildren, parent: "/components" });

      // Add API menu children to the vuex store.
      const apiIndex = await $content("api").only(["path", "title"]).fetch();
      commit("addMenuChildren", {
        children: sectionChildren(apiIndex),
        parent: "/api",
      });
    } catch (err) {
      console.log(err)
    }
  }
}
