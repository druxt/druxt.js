const sectionChildren = (index) => index.map((o) => ({
  component: "NuxtLink",
  text: o.title,
  props: { to: o.path.replace("/README", "") },
}));

export const actions = {
  async nuxtServerInit({ commit }, { $content }) {
    try {
      // Add Druxt modules to Vuex store.
      const modulesIndex = await $content("api/README").only("toc").fetch()
      const modules = await Promise.all(modulesIndex.toc
        .filter((o) => o.id !== 'druxt')
        .map((o) =>
          $content(`modules/${o.id.split("-")[1]}/README`)
            .only(["description", "dir", "title"])
            .fetch()
            .catch(() => null)
        )
      )
      // Filtered once for both uses: the README documents are generated by
      // build:docs, and on a checkout that has not run it every fetch
      // returns null. Mapping the unfiltered array threw here and the catch
      // then killed the rest of nuxtServerInit, collapsing every nav
      // section, not just Modules.
      const available = modules.filter(Boolean);
      commit("setModules", available);

      // Add Modules menu children to the vuex store.
      const moduleChildren = available
        .map((o) => ({
          component: "NuxtLink",
          text: o.title,
          props: { to: o.dir },
        }));
      commit("addMenuChildren", { children: moduleChildren, parent: "/modules" });

      // Add the Diataxis section menu children to the Vuex store.
      for (const section of ["tutorials", "how-to", "explanation"]) {
        const index = await $content(section)
          .sortBy("weight")
          .only(["path", "title", "weight"])
          .fetch();
        commit("addMenuChildren", {
          children: sectionChildren(index),
          parent: `/${section}`,
        });
      }

      // Add API menu children to the Vuex store: one entry per package,
      // each carrying its own pages for the sidebar's third level.
      // Component reference pages ride at depth two of each package.
      const apiDocs = await $content("api/packages", { deep: true })
        .only(["path", "title"])
        .fetch();
      const packages = {};
      const hasIndex = {};
      for (const doc of apiDocs) {
        const [, , , pkg, ...rest] = doc.path.split("/");
        if (!packages[pkg]) packages[pkg] = [];
        if (rest.length === 1 && rest[0] === "index") {
          hasIndex[pkg] = true;
          continue;
        }
        if (!rest.length || rest.length > 2) continue;
        packages[pkg].push({
          component: "NuxtLink",
          text: doc.title,
          props: { to: doc.path.replace(/\/index$/, "") },
          group: rest.length === 2 ? rest[0] : "",
        });
      }
      const apiChildren = Object.keys(packages).sort().map((pkg) => {
        const children = packages[pkg].sort((a, b) => (
          a.group === b.group ? (a.text < b.text ? -1 : 1) : (a.group < b.group ? -1 : 1)
        ));
        // A package without an index page (test-utils) links to its first
        // reference page, so the entry never points at a 404.
        const to = hasIndex[pkg] || !children.length
          ? `/api/packages/${pkg}`
          : children[0].props.to;
        return {
          component: "NuxtLink",
          text: pkg.charAt(0).toUpperCase() + pkg.slice(1),
          props: { to },
          children,
        };
      });
      commit("addMenuChildren", { children: apiChildren, parent: "/api" });
    } catch (err) {
      console.log(err)
    }
  }
}
