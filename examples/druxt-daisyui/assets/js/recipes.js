import { DrupalJsonApiParams } from 'drupal-jsonapi-params'

const TYPE = 'node--recipe'

const query = () =>
  new DrupalJsonApiParams()
    .addFilter('status', '1')
    .addSort('created', 'DESC')
    .addFields(TYPE, [
      'title',
      'field_summary',
      'field_difficulty',
      'field_preparation_time',
      'field_cooking_time',
      'field_media_image',
      'field_recipe_category',
    ])
    .addInclude([
      'field_media_image',
      'field_media_image.field_media_image',
      'field_recipe_category',
    ])
    .addFields('media--image', ['field_media_image'])
    .addFields('file--file', ['uri'])
    .addFields('taxonomy_term--recipe_category', ['name'])

export async function fetchRecipes(store) {
  const resources = await store.dispatch('druxt/getCollection', {
    type: TYPE,
    query: query(),
  })
  const included = Object.fromEntries(
    (resources.included || []).map((resource) => [resource.id, resource])
  )
  return resources.data.map((resource) => toRecipe(resource, included))
}

// Relationship data is an array for multi-value fields (category) and a
// plain object for single-value fields (image refs) - normalize to the
// first reference either way.
const first = (relationship) => {
  const data = (relationship || {}).data
  return Array.isArray(data) ? data[0] : data
}

export function toRecipe(resource, included) {
  const attributes = resource.attributes
  const mediaRef = first(resource.relationships.field_media_image)
  const media = mediaRef && included[mediaRef.id]
  const fileRef = media && first(media.relationships.field_media_image)
  const file = fileRef && included[fileRef.id]
  const categoryRef = first(resource.relationships.field_recipe_category)
  const term = categoryRef && included[categoryRef.id]
  const uri = file && file.attributes.uri.value
  const relative = uri && uri.replace(/^public:\/\//, '')
  const summary = attributes.field_summary
  return {
    id: resource.id,
    title: attributes.title,
    // Real backend image styles (pre-generated by the provision script),
    // instead of shipping the full-size originals to a 4:3 card / small
    // tile: druxt_card_4_3 (600x450) for the deck, druxt_thumb_4_3
    // (240x180) for the box tiles.
    img:
      relative &&
      `/sites/default/files/styles/druxt_card_4_3/public/${relative}`,
    thumb:
      relative &&
      `/sites/default/files/styles/druxt_thumb_4_3/public/${relative}`,
    summary:
      typeof summary === 'string'
        ? summary
        : (summary && (summary.processed || summary.value || '')) || '',
    difficulty: attributes.field_difficulty,
    prep: attributes.field_preparation_time || 0,
    cook: attributes.field_cooking_time || 0,
    category: term && term.attributes.name,
  }
}

export async function fetchCategories(store) {
  const type = 'taxonomy_term--recipe_category'
  const resources = await store.dispatch('druxt/getCollection', {
    type,
    query: new DrupalJsonApiParams()
      .addFields(type, ['name'])
      .addSort('weight', 'ASC'),
  })
  return resources.data.map((resource) => resource.attributes.name)
}
